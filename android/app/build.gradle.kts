// Server URL comes from local.properties (see local.properties.example); it defaults to the demo server.
val local = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun localProp(key: String, default: String = "") = (local.getProperty(key) ?: default).replace("\"", "")

// Play upload key: keystore.properties (git-ignored) with storeFile, storePassword, keyAlias, keyPassword.
val keystore = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "app.bizzassist.agent"
    compileSdk = 36

    defaultConfig {
        applicationId = "app.bizzassist.agent"
        minSdk = 24
        targetSdk = 36
        versionCode = 2
        versionName = "2.0"

        val apiBase = localProp("bizzassist.apiBaseUrl", "https://bizzassist.biz/").let { if (it.endsWith("/")) it else "$it/" }
        buildConfigField("String", "API_BASE_URL", "\"$apiBase\"")
    }

    signingConfigs {
        if (keystore.isNotEmpty()) create("upload") {
            storeFile = file(keystore.getProperty("storeFile"))
            storePassword = keystore.getProperty("storePassword")
            keyAlias = keystore.getProperty("keyAlias")
            keyPassword = keystore.getProperty("keyPassword")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            // Without keystore.properties the release falls back to the debug key, so anyone can build a sideloadable APK.
            signingConfig = signingConfigs.findByName("upload") ?: signingConfigs.getByName("debug")
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

